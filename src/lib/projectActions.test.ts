import { describe, it, expect, vi } from "vitest";
vi.mock("@/integrations/supabase/client", () => ({ supabase: {} }));
import { collectFiles, copyName, restoredStatus, isArchived } from "./projectActions";

describe("project actions", () => {
  it("names copies without stacking suffixes", () => {
    expect(copyName("Office", [])).toBe("Office (copy)");
    expect(copyName("Office", ["Office (copy)"])).toBe("Office (copy 2)");
    expect(copyName("Office (copy)", ["Office (copy)", "Office (copy 2)"])).toBe("Office (copy 3)");
  });
  it("restores to active only when the experience was generated", () => {
    const spatial = { mode: "multipoint", qr_code_url: "p/qr_code.png" };
    expect(restoredStatus({ ...spatial, mind_file_url: "p/targets.mind", share_link: "abc" })).toBe("active");
    expect(restoredStatus({ ...spatial, mind_file_url: null, share_link: "abc" })).toBe("draft");
    expect(restoredStatus({ ...spatial, mind_file_url: "p/targets.mind", share_link: null })).toBe("draft");
  });
  it("Spatial counts as generated by its marker images (8th Wall, no .mind since 17 Nov 2026)", () => {
    const spatial = { mode: "multipoint", qr_code_url: "p/qr_code.png", mind_file_url: null };
    const markers = { "1": "p/markers/marker_1.png", "2": "p/markers/marker_2.png", "3": "p/markers/marker_3.png" };
    expect(restoredStatus({ ...spatial, marker_image_urls: markers, share_link: "abc" })).toBe("active");
    expect(restoredStatus({ ...spatial, marker_image_urls: {}, share_link: "abc" })).toBe("draft");
    expect(restoredStatus({ ...spatial, marker_image_urls: null, share_link: "abc" })).toBe("draft");
    expect(restoredStatus({ ...spatial, marker_image_urls: markers, share_link: null })).toBe("draft");
  });
  it("Tabletop/Wall count as generated by their QR, not a .mind file", () => {
    for (const mode of ["tabletop", "wall"]) {
      expect(restoredStatus({ mode, mind_file_url: null, qr_code_url: "p/qr_code.png", share_link: "abc" })).toBe("active");
      expect(restoredStatus({ mode, mind_file_url: "p/targets.mind", qr_code_url: null, share_link: "abc" })).toBe("draft");
      expect(restoredStatus({ mode, mind_file_url: null, qr_code_url: "p/qr_code.png", share_link: null })).toBe("draft");
    }
  });
  it("detects archived", () => {
    expect(isArchived({ status: "archived" })).toBe(true);
    expect(isArchived({ status: "active" })).toBe(false);
  });
});

describe("collectFiles", () => {
  // The shape a real Spatial project leaves in storage (16 Nov 2026).
  const tree: Record<string, { name: string; id: string | null }[]> = {
    "p1": [
      { name: "qr_code.png", id: "a" },
      { name: "targets.mind", id: "b" },
      { name: "thumbnail-v2.jpg", id: "c" },
      { name: "markers", id: null },
      { name: "mwj7ihau", id: null },
    ],
    "p1/markers": [{ name: "marker_1.png", id: "d" }, { name: "marker_2.png", id: "e" }],
    "p1/mwj7ihau": [{ name: "koekken_archiar.glb", id: "f" }],
  };
  const list = async (path: string) => tree[path] ?? [];

  it("walks sub-folders: models and marker images sit one level down", async () => {
    expect((await collectFiles(list, "p1")).sort()).toEqual([
      "p1/markers/marker_1.png",
      "p1/markers/marker_2.png",
      "p1/mwj7ihau/koekken_archiar.glb",
      "p1/qr_code.png",
      "p1/targets.mind",
      "p1/thumbnail-v2.jpg",
    ]);
  });

  it("returns nothing for a project without files", async () => {
    expect(await collectFiles(list, "p2")).toEqual([]);
  });

  it("stops at the depth limit instead of walking forever", async () => {
    const loop = async () => [{ name: "again", id: null }];
    expect(await collectFiles(loop, "p", 3)).toEqual([]);
  });
});
