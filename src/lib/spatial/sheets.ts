/**
 * Spatial A4 print layouts (210 × 297 mm), built as SVG strings.
 *
 *  - markerSheetSvg: location-marker sheet (locked v7) — 210 × 210 top card with
 *    title, logo, disc Ø150 mm and POINT n pill; dotted cut line; info strip with
 *    X/Y/Z pills, origin row, placement steps and the round QR.
 *  - qrPageSvg: client QR page — same logic, round QR badge instead of the disc.
 *
 * Fonts are embedded (see fonts.ts) so the SVG renders the same when it is
 * rasterised through an <img>.
 */
import { BRAND, INK, escapeXml, logoTile, markerDiscInner } from "@/lib/spatial/design";
import { spatialQrInner } from "@/lib/spatial/qr";

export const SHEET_W = 210;
export const SHEET_H = 297;

export interface MarkerSheetInput {
  index: number;
  x: number;
  y: number;
  z: number;
  /** Placement label shown under the project name. */
  label?: string;
  projectName: string;
  /** Marker colour (#RRGGBB). */
  color: string;
  shareUrl: string;
  /** Two lines describing where the model's 0,0,0 sits. Defaults to a generic note. */
  originNote?: [string, string];
}

/** Relative luminance (0–1) of a #RRGGBB colour. */
function luminance(hex: string): number {
  const h = hex.replace("#", "");
  const ch = [0, 2, 4].map((i) => {
    const v = parseInt(h.slice(i, i + 2), 16) / 255;
    return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4);
  });
  return 0.2126 * ch[0] + 0.7152 * ch[1] + 0.0722 * ch[2];
}

/** Text colour on a filled marker-colour pill: white, or ink on light colours (e.g. yellow). */
function onColor(col: string): string {
  return luminance(col) > 0.4 ? INK : "#fff";
}

/** Marker colour for small text on white/grey: unchanged, or darkened on light colours. */
function accentText(col: string): string {
  if (luminance(col) <= 0.4) return col;
  const h = col.replace("#", "");
  const mix = [0, 2, 4].map((i) => Math.round(parseInt(h.slice(i, i + 2), 16) * 0.55));
  return "#" + mix.map((v) => v.toString(16).padStart(2, "0")).join("");
}

const GREY = "#6b7280";
const CUT = "#9ca3af";

function wrap(inner: string, fontCss: string): string {
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SHEET_W} ${SHEET_H}" width="${SHEET_W}" height="${SHEET_H}" font-family="Inter, sans-serif">` +
    `<style>${fontCss}</style>${inner}</svg>`
  );
}

/** Dotted cut line at y = 210 with scissors and caption. */
function cutLine(): string {
  const dash = `stroke="${CUT}" stroke-width=".4" stroke-dasharray="1.2 1.6" stroke-linecap="round"`;
  return (
    `<line x1="8" y1="210" x2="84" y2="210" ${dash}/><line x1="144" y1="210" x2="202" y2="210" ${dash}/>` +
    `<text x="119" y="211.2" text-anchor="middle" font-size="2.8" letter-spacing=".6" fill="${CUT}" font-weight="600">CUT HERE · OPTIONAL</text>` +
    `<g stroke="${CUT}" stroke-width=".4" fill="none"><circle cx="91.3" cy="211.4" r=".9"/><circle cx="91.3" cy="208.6" r=".9"/>` +
    `<path d="M92 208.9 L95.5 210.7 M92 211.1 L95.5 209.3" stroke-linecap="round"/></g>`
  );
}

function header(title: string, sub: string): string {
  return (
    `<text x="17" y="24" font-size="8" font-weight="700" fill="${INK}">${escapeXml(title)}</text>` +
    `<text x="17" y="30" font-size="4" fill="${GREY}">${escapeXml(sub)}</text>` +
    `<text x="193" y="23.6" text-anchor="end" font-family="Space Grotesk" font-size="6" font-weight="700" fill="${INK}">Archi AR</text>` +
    logoTile(162.6, 21.7, 4.4)
  );
}

function footer(): string {
  return `<text x="105" y="293.5" text-anchor="middle" font-size="2.6" letter-spacing=".5" fill="${CUT}">Generated by Archi AR</text>`;
}

function pill(x: number, y: number, w: number, label: string, col: string): string {
  const fg = onColor(col);
  return (
    `<rect x="${x}" y="${y}" width="${w}" height="11" rx="5.5" fill="${col}"/>` +
    `<text x="${x + w / 2}" y="${y + 7.2}" text-anchor="middle" font-size="5" font-weight="700" letter-spacing=".8" fill="${fg}">${label}</text>`
  );
}

// ── Location-marker sheet ───────────────────────────────────────────────────

export function markerSheetSvg(input: MarkerSheetInput, fontCss: string): string {
  const { index, projectName, color: col, shareUrl } = input;
  const label = input.label || `Marker ${index}`;
  const originNote = input.originNote ?? [
    "Same point as 0,0,0 in the Rhino model",
    "Measure X, Y, Z from the model's origin",
  ];
  const ac = accentText(col);
  let s = `<rect width="${SHEET_W}" height="${SHEET_H}" fill="#fff"/>`;

  // top card 210 × 210
  s += `<rect x="6" y="6" width="198" height="198" rx="9" fill="none" stroke="${col}" stroke-width=".7"/>`;
  s += `<rect x="9.5" y="9.5" width="191" height="191" rx="6.5" fill="none" stroke="${col}" stroke-opacity=".25" stroke-width=".25"/>`;
  s += header(projectName, label);

  // disc Ø150 mm (= MARKER_SIZE_MM), centre (105, 105), plus N/E/S/W alignment ticks
  s += `<g transform="translate(30 30) scale(${150 / 1200})">${markerDiscInner(index, col)}</g>`;
  for (const [dx, dy] of [[0, -1], [1, 0], [0, 1], [-1, 0]]) {
    s += `<line x1="${105 + dx * 77.5}" y1="${105 + dy * 77.5}" x2="${105 + dx * 82}" y2="${105 + dy * 82}" stroke="${INK}" stroke-width=".35"/>`;
  }
  s += pill(17, 184, 38, `POINT ${index}`, col);

  s += cutLine();

  // info strip
  s += `<text x="17" y="218" font-size="3" letter-spacing=".6" fill="${GREY}" font-weight="600">DISC Ø 150 MM · CENTRE = COORDINATE · FACING THE MODEL FROM THE FRONT</text>`;
  const px = [17, 75, 133];
  const notes = ["left  ←  →  right (+)", "toward  ↓  ↑  away (+)", "down  ↓  ↑  up (+)"];
  const values = [input.x, input.y, input.z];
  ["X", "Y", "Z"].forEach((k, i) => {
    s +=
      `<rect x="${px[i]}" y="222" width="56" height="17" rx="6" fill="#f3f4f6"/>` +
      `<text x="${px[i] + 6}" y="229.6" font-size="4.2" font-weight="700" fill="${ac}">${k}</text>` +
      `<text x="${px[i] + 50}" y="229.6" text-anchor="end" font-size="5" font-weight="600" fill="${INK}" font-family="Geist Mono, monospace">${values[i]} <tspan font-size="3.2" fill="${GREY}">mm</tspan></text>` +
      `<text x="${px[i] + 6}" y="235.4" font-size="2.9" fill="${GREY}">${notes[i]}</text>`;
  });

  // origin row: mini plan sketch + text
  s += `<rect x="17" y="243" width="120" height="17" rx="6" fill="#f3f4f6"/>`;
  const ox = 24;
  const oy = 254.5;
  s +=
    `<rect x="${ox}" y="${oy - 8}" width="13" height="8" rx="1" fill="#fff" stroke="${INK}" stroke-width=".35"/>` +
    `<line x1="${ox}" y1="${oy}" x2="${ox + 9}" y2="${oy}" stroke="${col}" stroke-width=".5"/><line x1="${ox}" y1="${oy}" x2="${ox}" y2="${oy - 6}" stroke="${col}" stroke-width=".5"/>` +
    `<circle cx="${ox}" cy="${oy}" r="1.2" fill="${col}"/>` +
    `<text x="${ox + 9.6}" y="${oy + 0.8}" font-size="2.2" font-weight="700" fill="${col}">X</text><text x="${ox - 3}" y="${oy - 5.2}" font-size="2.2" font-weight="700" fill="${col}">Y</text>`;
  s +=
    `<text x="45" y="249.4" font-size="2.9" letter-spacing=".5" font-weight="700" fill="${ac}">MODEL ORIGIN (0, 0, 0)</text>` +
    `<text x="45" y="254.6" font-size="3.6" font-weight="600" fill="${INK}">${escapeXml(originNote[0])}</text>` +
    `<text x="45" y="258.1" font-size="2.7" fill="${GREY}">${escapeXml(originNote[1])}</text>`;

  // placement steps
  s += `<text x="17" y="268" font-size="3.4" font-weight="700" letter-spacing=".6" fill="${INK}">PLACEMENT</text>`;
  [
    "Print at 100% — no fit-to-page.",
    "Fix flat; disc centre on the coordinate.",
    "Matte surface, even light, unobstructed.",
    "Place at least 3 points, then scan the QR.",
  ].forEach((t, i) => {
    s += `<text x="17" y="${273.5 + i * 4.6}" font-size="3.3" fill="#4b5563"><tspan font-weight="700" fill="${ac}">${i + 1}</tspan>  ${t}</text>`;
  });

  // round QR, bottom right of the info strip (no text label)
  s += `<svg x="142" y="241" width="50" height="50" viewBox="0 0 1000 1000">${spatialQrInner(shareUrl, "round")}</svg>`;
  s += footer();
  return wrap(s, fontCss);
}

// ── Client QR page ──────────────────────────────────────────────────────────

export interface QrPageInput {
  projectName: string;
  shareUrl: string;
  /** Accent for the SCAN ME pill and step numbers; defaults to the brand blue. */
  color?: string;
}

export function qrPageSvg(input: QrPageInput, fontCss: string): string {
  const col = input.color ?? BRAND;
  let s = `<rect width="${SHEET_W}" height="${SHEET_H}" fill="#fff"/>`;

  s += header(input.projectName, "Scan to launch the AR experience");
  // round QR badge 140 mm, centred; no outline frames on this page
  s += `<svg x="35" y="38" width="140" height="140" viewBox="0 0 1000 1000">${spatialQrInner(input.shareUrl, "round")}</svg>`;
  s += pill(17, 187, 50, "SCAN ME", col);
  s += cutLine();

  s += `<text x="17" y="221" font-size="3" letter-spacing=".6" fill="${GREY}" font-weight="600">QR CODE · LAUNCHES THE AR EXPERIENCE · FOR THE CLIENT</text>`;
  const px = [17, 77, 137];
  const titles = ["Scan", "Allow", "Aim"];
  const lines: [string, string][] = [
    ["Open the phone camera", "and scan the code"],
    ["Accept camera access", "in the browser"],
    ["Point at the location", "markers in the room"],
  ];
  titles.forEach((k, i) => {
    s +=
      `<rect x="${px[i]}" y="227" width="56" height="25" rx="6" fill="#f3f4f6"/>` +
      `<circle cx="${px[i] + 9}" cy="239.5" r="4.6" fill="${col}"/>` +
      `<text x="${px[i] + 9}" y="241.2" text-anchor="middle" font-size="4.6" font-weight="700" fill="#fff">${i + 1}</text>` +
      `<text x="${px[i] + 17.5}" y="237.6" font-size="4.6" font-weight="700" fill="${INK}">${k}</text>` +
      `<text x="${px[i] + 17.5}" y="242.6" font-size="2.9" fill="${GREY}">${lines[i][0]}</text>` +
      `<text x="${px[i] + 17.5}" y="246.2" font-size="2.9" fill="${GREY}">${lines[i][1]}</text>`;
  });

  s += `<rect x="17" y="259" width="176" height="28" rx="6" fill="none" stroke="#e5e7eb" stroke-width=".4"/>`;
  s += `<text x="23" y="265.4" font-size="3" font-weight="700" letter-spacing=".6" fill="${col}">PLACEMENT</text>`;
  const tips: [string, string][] = [
    ["Print at 100%", "no fit-to-page"],
    ["Start of the visit", "e.g. at the entrance"],
    ["Matte surface", "no glare on the code"],
    ["Keep markers in place", "while the client scans"],
  ];
  tips.forEach((t, i) => {
    const x = 23 + (i % 2) * 84;
    const y = 271.6 + Math.floor(i / 2) * 8.6;
    s +=
      `<circle cx="${x + 1.2}" cy="${y - 1.1}" r="1.2" fill="${col}"/>` +
      `<text x="${x + 4.5}" y="${y}" font-size="3.4" font-weight="600" fill="${INK}">${t[0]}</text>` +
      `<text x="${x + 4.5}" y="${y + 3.6}" font-size="2.8" fill="${GREY}">${t[1]}</text>`;
  });
  s += footer();
  return wrap(s, fontCss);
}
